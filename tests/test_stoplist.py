import pytest

from telegram_net.stoplist import find_stop_topic


@pytest.mark.parametrize(
    "text",
    [
        "У Житомирі працівники ТЦК зупинили авто",
        "Представники територіального центру комплектування прийшли на ринок",
        "В області триває мобілізація",
        "Соцмережі обговорюють бусифікацію",
        "Чоловікові вручили повістку",
        "Суд оштрафував ухилянта",
        "Оновлено правила для військовозобов'язаних",
        "Сотрудники военкомата задержали мужчину",
    ],
)
def test_stop_topics_are_caught(text):
    assert find_stop_topic(text)


@pytest.mark.parametrize(
    "text",
    [
        "У Малині відремонтували міст через Ірпінь",
        "Рятувальники ліквідували пожежу в Коростені",
        "Школи громади переходять на онлайн-навчання",
        "Футбольний матч завершився перемогою",  # «матч» не має чіпляти «ТЦК»
    ],
)
def test_ordinary_news_passes(text):
    assert find_stop_topic(text) is None
