"""Теми, яких мережа не торкається взагалі: ТЦК, мобілізація, «бусифікація».

Фільтр стоїть двічі: на вході (collect — такі новини навіть не показуються
редактору) і на виході (publish — пост із таким словом не буде надіслано, хоч би
що вирішив редактор). Це свідомо грубий фільтр за коренями слів: краще втратити
одну нейтральну новину зі словом «мобілізація», ніж пропустити небажану тему.
"""

from __future__ import annotations

import re

_PATTERNS = (
    r"\bтцк\b",
    r"\bтцк\s*та\s*сп\b",
    r"територіальн\w*\s+центр\w*\s+комплектуван\w*",
    r"центр\w*\s+комплектуван\w*",
    r"військкомат\w*",
    r"воєнком\w*",
    r"мобілізац\w*",
    r"мобілізов\w*",
    r"бусифік\w*",
    r"повістк\w*",
    r"ухилянт\w*",
    r"ухилен\w*\s+від\s+(?:мобілізац|служб|призов)\w*",
    r"військовозобов.?язан\w*",
    # російськомовні джерела
    r"\bтцк\s*и\s*сп\b",
    r"военкомат\w*",
    r"мобилизац\w*",
    r"бусифик\w*",
    r"повестк\w*",
    r"уклонист\w*",
)
_STOP_RE = re.compile("|".join(_PATTERNS), re.IGNORECASE)


def find_stop_topic(text: str) -> str | None:
    """Повертає знайдений фрагмент (для логу/пояснення) або None."""
    match = _STOP_RE.search(text or "")
    return match.group(0) if match else None
