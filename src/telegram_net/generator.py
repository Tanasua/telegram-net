"""Другий LLM-крок: сам пост. Варіативність стилю (довжина/заголовок) вирішується
до виклику (style.pick_style), тут вона тільки виконується — так розподіл
короткі/довгі/з заголовком/без гарантований кодом, а не 'сподіванням' на модель.

Формат постів змодельовано на реальному живому прикладі — телеграм-канал УНІАН
(t.me/uniannet): перевірено 2 незалежними вибірками останніх постів (2026-08-15).
Підтверджені спостереження: 7 з 8 постів — БЕЗ жодного емодзі (емодзі — не
формат каналу, на відміну від Главреда, який моделювали раніше); короткі
декларативні речення по суті, без риторики; заголовок — перше речення як
самодостатній факт, без клікбейту; хештегів не використовують; фіксованого
закінчення посту нема. Мова постів УНІАН у вибірці здебільшого російська —
цю деталь свідомо НЕ переносимо: наші канали українською для мешканців
Житомирщини, переймаємо лише сухий фактологічний тон і коротку структуру.
"""

from __future__ import annotations

from telegram_net.fetchers.base import FetchedItem
from telegram_net.llm import build_openai_client, require_model
from telegram_net.style import PostStyle

_LENGTH_GUIDANCE = {
    "short": "1-2 речення всього (сам факт-заголовок + щонайбільше одне уточнення). Без цитати.",
    "medium": "3-4 речення: факт-заголовок + 1-2 речення деталей, за наявності — коротка цитата з джерела.",
    "long": "5-6 речень: факт-заголовок + розгорнутий виклад деталей, з цитатою з джерела, якщо вона там є.",
}

_HEADLINE_ON = (
    "перше речення — самодостатній факт-заголовок (хто/що/де сталося), стисло й без "
    "вступних слів; одразу продовжуй звичайним текстом того ж абзацу, БЕЗ окремого "
    "рядка й БЕЗ порожнього рядка між заголовком і рештою"
)
_HEADLINE_OFF = (
    "без окремого заголовка-факту — почни з короткого контексту (де/коли), а головний "
    "факт подай у другому речення; так само одним суцільним текстом"
)

_SYSTEM_PROMPT = """Ти пишеш пост для телеграм-каналу місцевих новин міста "{region}".
Стиль — сухий, фактологічний, як у новинного агентства (УНІАН), а не вигаданий:

- БЕЗ ЖОДНОГО емодзі — ні на початку, ні в тексті посту.
- {headline_instruction}
- Речення короткі й декларативні (орієнтовно 8-20 слів), без нагромадження підрядних
  через кому. Без риторичних питань і без клікбейтних формулювань.
- Якщо в наданому джерелі є пряма цитата людини — можна включити її в лапках з
  атрибуцією (напр. «...», — сказав/повідомив Х). Якщо цитати в джерелі НЕМАЄ —
  НІКОЛИ не вигадуй її сам, просто викладай факти без цитати.
- Без хештегів.
- Пост має бути ПРО ОДНУ новину. Якщо надане джерело саме по собі — це дайджест
  на кілька різних тем в одному повідомленні (напр. "спорт, школа і ще щось —
  що сьогодні у місті"), НЕ намагайся згадати все. Обери ОДНУ найважливішу/
  найцікавішу тему з нього і напиши пост лише про неї, решту тем із джерела
  просто ігноруй повністю — категорично не роби "збірну солянку" з кількох
  новин в одному пості.

Довжина цього конкретного посту: {length_guidance}

Пиши українською, за фактами з наданого тексту-джерела. Не додавай фактів, яких
там немає. Не пиши "за повідомленням джерела" чи подібні канцеляризми — просто подай
як новину каналу. Виведи лише текст самого посту, без приміток від себе."""


def build_prompt(item: FetchedItem, style: PostStyle, region_name: str) -> list[dict]:
    headline_instruction = _HEADLINE_ON if style.with_headline else _HEADLINE_OFF
    system = _SYSTEM_PROMPT.format(
        region=region_name,
        length_guidance=_LENGTH_GUIDANCE[style.length],
        headline_instruction=headline_instruction,
    )
    source_text = item.text.strip() or (
        "(джерело без тексту — лише фото/відео, опиши коротко на основі контексту URL)"
    )
    return [
        {"role": "system", "content": system},
        {"role": "user", "content": f"Джерело: {item.url}\n\nТекст джерела:\n{source_text}"},
    ]


class Generator:
    def __init__(self, client=None, model: str | None = None):
        self._client = client or build_openai_client()
        self.model = model or require_model("OPENAI_GENERATOR_MODEL")

    def generate(self, item: FetchedItem, style: PostStyle, region_name: str) -> str:
        messages = build_prompt(item, style, region_name)
        completion = self._client.chat.completions.create(model=self.model, messages=messages)
        text = completion.choices[0].message.content
        if not text:
            raise RuntimeError("OpenAI не повернув текст посту")
        return text.strip()
